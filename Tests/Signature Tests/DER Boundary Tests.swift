import Byte
import Testing

@testable import Signature

@Suite
struct `PKCS8 DER unwrap boundaries` {
    private func unwrap(_ bytes: [UInt8]) throws(Signature.RSA.Key.Error) -> [Byte] {
        try Signature.RSA.Key.unwrap(bytes.map { Byte($0) })
    }

    @Test
    func `the smallest well-formed wrapper yields its key bytes`() throws {
        #expect(try unwrap([0x30, 0x08, 0x02, 0x00, 0x30, 0x00, 0x04, 0x02, 0xAA, 0xBB]) == [0xAA, 0xBB].map { Byte($0) })
    }

    @Test
    func `a long-form key length is read`() throws {
        #expect(try unwrap([0x30, 0x81, 0x09, 0x02, 0x00, 0x30, 0x00, 0x04, 0x81, 0x01, 0x07]) == [Byte(0x07)])
    }

    @Test(arguments: [
        [UInt8](),
        [0x31, 0x00],
        [0x30, 0x80, 0x02, 0x00],
        [0x30, 0x85, 0x00, 0x00, 0x00, 0x00, 0x01],
        [0x30, 0x06, 0x02, 0x84, 0xFF, 0xFF, 0xFF, 0xFF],
        [0x30, 0x06, 0x02, 0x00, 0x30, 0x00, 0x04, 0x05, 0xAA],
        [0x30, 0x04, 0x02, 0x00, 0x30, 0x00],
    ])
    func `malformed DER is rejected without trapping`(_ bytes: [UInt8]) {
        #expect(throws: Signature.RSA.Key.Error.malformed) { try unwrap(bytes) }
    }
}
